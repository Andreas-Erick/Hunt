// Bundles the shared domain core (src/mobile/huntCore.ts) into the phone page.
//
//   node scripts/build-mobile-core.mjs          rewrite the generated block in both HTML copies
//   node scripts/build-mobile-core.mjs --check  exit 1 when a copy is stale (CI / pre-APK)
//
// The block sits between the HUNT-CORE markers in public/hunt-mobile.html and is mirrored
// byte-for-byte into android-app/app/src/main/assets/hunt-mobile.html (build-apk.sh and
// mobileMirror.test.ts require the two copies to be identical).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const ENTRY = path.join(ROOT, "src", "mobile", "huntCore.ts");
export const HTML_COPIES = [
  path.join(ROOT, "public", "hunt-mobile.html"),
  path.join(ROOT, "android-app", "app", "src", "main", "assets", "hunt-mobile.html"),
];
export const BEGIN = "<!-- HUNT-CORE:BEGIN generated by scripts/build-mobile-core.mjs from src/mobile/huntCore.ts; do not edit -->";
export const END = "<!-- HUNT-CORE:END -->";

/** The generated block (markers included) for the current sources. */
export async function buildCoreBlock() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    globalName: "HuntCore",
    platform: "browser",
    target: "es2019",
    charset: "utf8",
    legalComments: "none",
    logLevel: "silent",
  });
  const code = result.outputFiles[0].text.replace(/\r\n/g, "\n").trimEnd();
  return `${BEGIN}\n  <script>\n${code}\n  </script>\n  ${END}`;
}

/**
 * `html` with its generated block replaced by `block`, written in the file's own
 * line-ending style (a Windows checkout with core.autocrlf has CRLF).
 */
export function withCoreBlock(html, block) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a === -1 || b === -1 || b < a) {
    throw new Error("hunt-mobile.html has no HUNT-CORE:BEGIN/END markers");
  }
  const eol = html.includes("\r\n") ? "\r\n" : "\n";
  return html.slice(0, a) + block.replace(/\n/g, eol) + html.slice(b + END.length);
}

async function main() {
  const check = process.argv.includes("--check");
  const block = await buildCoreBlock();
  let stale = false;
  for (const file of HTML_COPIES) {
    const html = readFileSync(file, "utf8");
    const next = withCoreBlock(html, block);
    if (next === html) continue;
    stale = true;
    if (check) {
      console.error(`stale HuntCore block: ${path.relative(ROOT, file)}`);
    } else {
      writeFileSync(file, next);
      console.log(`updated ${path.relative(ROOT, file)}`);
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("HuntCore block is up to date");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
